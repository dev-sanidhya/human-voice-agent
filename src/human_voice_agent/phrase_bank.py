"""The cacheable phrase library: every complete, fixed, reusable utterance
in the agent's vocabulary, organized by when it gets used.

Why *phrases*, not words: TTS caching only helps naturalness-neutral when
the cached unit is something a person would actually say as one breath.
Gluing together separately-synthesized individual words has no natural
coarticulation or sentence-level prosody across the joins - it's the
"robocall from 2005" sound, and it would work directly against the whole
point of this project (sounding human). A word-frequency list (the usual
meaning of "top 500 words") is built for text/reading-level analysis, not
for concatenative speech - there's no publicly meaningful "top 500 phrases"
corpus for a customer-service phone agent either, so these are hand-written
the same way the original backchannel pool was: real, complete phrases a
person would actually say in this context, not a frequency list.

Confirmed live and worth stating plainly: padding this file with phrases
just to hit a round number would cost real money for zero benefit. Every
phrase warmed here is a real TTS call, billed per character
(tts_fallback.py / the cost breakdown given in chat). A phrase that's in
the pool but has no real chance of being selected - or worse, that nothing
in the pipeline ever triggers at all - is money spent on audio nobody
hears. That's not hypothetical: it's exactly what was happening with HOLD
before this pass (see below), confirmed and fixed in this revision.

Three categories now, not four - GREETING, ACK (which now *includes* what
used to be a separate, unwired HOLD category), and CLOSING:

- greeting: the opening line. Previously generated by the LLM on every
  call (confirmed live: costs a full LLM+TTS round trip - the caller hears
  nothing for 1-2s+ at the very start of every single call, before they've
  said anything at all). Cached, it's instant - see run_local.py.
- ack: everything backchannel.py's choose_backchannel() can actually pick
  when a turn ends - short acknowledgments ("yeah,", "got it,") *and* the
  phrases that used to live in a separate HOLD category ("let me check
  that for you"). Merging them was a real fix, not just a rename: HOLD
  was cached (real money spent synthesizing it) but nothing in the
  pipeline ever selected it - confirmed live, 100% wasted spend. Folding
  it into the same pool choose_backchannel() already draws from means
  every phrase warmed here now has a real, working trigger, and the
  larger combined pool is a genuine naturalness win too - less repetition
  across a longer call. Also includes a handful of hybrid phrases that
  chain a short ack straight into a stall in one breath ("mm, got it, let
  me check that for you") - the way people actually talk, not strictly
  one or the other.
- closing: sign-off lines for a future "wrap up the call" flow that
  doesn't exist yet - no call-end detection is implemented anywhere in
  this pipeline. Deliberately *not* included in default warming
  (priority_phrases / what pipeline.py actually calls) for exactly the
  reason ack+hold got merged above: warming phrases nothing can trigger
  is real, avoidable cost for zero benefit. Written and kept here so
  wiring a real closing flow later is a one-line change, not a rewrite -
  but not warmed, not claimed as active, and excluded from the cost
  estimate accordingly.
"""

