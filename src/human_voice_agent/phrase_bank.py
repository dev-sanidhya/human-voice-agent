def priority_phrases(language: str) -> list[str]:
    """Everything with a real, working trigger in the pipeline right now:
    greeting (played at call start) and ack (selected by
    choose_backchannel throughout the call). This is what pipeline.py
    actually warms - CLOSING is deliberately not included; see the module
    docstring for why warming a phrase nothing can trigger is real,
    avoidable cost, not future-proofing.
    """
    return list(GREETING.get(language, GREETING["en"])) + list(ACK.get(language, ACK["en"]))


def all_cacheable_phrases(language: str) -> list[str]:
    """Every phrase in the library, including CLOSING - for auditing what
    exists, or for deliberately warming the not-yet-wired category anyway
    (e.g. testing it before building the trigger). Not what pipeline.py
    calls by default - see priority_phrases().
    """
    phrases = []
    for bank in (GREETING, ACK, CLOSING):
        phrases.extend(bank.get(language, bank["en"]))
    return phrases
